// Prints SQL that loads meeting transcripts into public.meetings for one board.
// Usage: node scripts/load_meetings.mjs <board id> <raw transcript files...> > meetings.sql
//   e.g. node scripts/load_meetings.mjs staging evals/data/b-cb-9/raw_*.txt
// Then run the SQL in the Supabase SQL editor (it runs as postgres, so RLS does not apply).
//
// Each file is a raw transcript, one utterance per line (the format evals/scripts/split_paragraphs.py
// reads). Titles and dates come from meetings.json next to the files. Rows get source 'upload' and
// external_id '<board>/<file name>', so re-running skips meetings already loaded. A re-run updates the
// title and date but never the transcript: suggestions and ticket highlights point at its offsets.
import { readFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

const [board, ...files] = process.argv.slice(2);
if (!board || !files.length) {
  console.error("Usage: node scripts/load_meetings.mjs <board id> <raw transcript files...>");
  process.exit(1);
}

const quote = (value) => `'${value.replace(/'/g, "''")}'`;
const manifests = new Map();
const manifestFor = (file) => {
  const path = join(dirname(file), "meetings.json");
  if (!manifests.has(path)) manifests.set(path, JSON.parse(readFileSync(path, "utf8")));
  return manifests.get(path);
};

const values = files.map((file) => {
  const name = basename(file);
  const meta = manifestFor(file).find((entry) => entry.file === name);
  if (!meta) throw new Error(`${name} is not listed in ${join(dirname(file), "meetings.json")}`);
  // The same normalisation as buildParagraphs (src/transcript.ts): one trimmed, non-empty line per paragraph.
  const transcript = readFileSync(file, "utf8")
    .replace(/^﻿/, "")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .join("\n");
  const externalId = `${board}/${name.replace(/^raw_/, "").replace(/\.txt$/, "")}`;
  return `  (${[quote(board), quote(meta.title), quote(meta.held_on), quote(transcript), "'upload'", quote(externalId)].join(", ")})`;
});

console.log(
  `-- Generated by scripts/load_meetings.mjs: ${files.length} meeting(s) for ${board}.\n` +
    `insert into public.meetings (board, title, held_on, transcript, source, external_id) values\n${values.join(",\n")}\n` +
    `on conflict (source, external_id) do update set title = excluded.title, held_on = excluded.held_on;`,
);
