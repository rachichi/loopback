#!/usr/bin/env node
// Build SQL that creates all 59 NYC community boards and their boundaries.
//
// Input:  the NYC Open Data "Community Districts" GeoJSON export (dataset 5crt-au7u).
// Output: one SQL file per borough in the output dir, each an upsert you can run in the SQL editor
//         or apply as a migration. Existing boards keep their name, ticket types and flags; only the
//         boundary is written. New boards copy the ticket types of m-cb-3.
//
// Usage:  node scripts/seed_boards.mjs <community-districts.geojson> [outDir] [--allow-partial]
// Env:    SIMPLIFY_DEG  Douglas-Peucker tolerance in degrees (default 0.00002, about 2 m). 0 disables.
//
// BoroCD = borough digit + two-digit district number (103 = Manhattan CB3, 309 = Brooklyn CB9).
// The dataset also holds joint interest areas (parks, airports) with numbers above each borough's
// district count. Those are dropped.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const allowPartial = process.argv.includes("--allow-partial");
const [input, outDir = "supabase/seeds/boards"] = args;
if (!input) {
  console.error("usage: node scripts/seed_boards.mjs <community-districts.geojson> [outDir] [--allow-partial]");
  process.exit(1);
}

const BOROUGHS = {
  1: { prefix: "m", name: "Manhattan", slug: "manhattan", count: 12 },
  2: { prefix: "bx", name: "Bronx", slug: "bronx", count: 12 },
  3: { prefix: "b", name: "Brooklyn", slug: "brooklyn", count: 18 },
  4: { prefix: "q", name: "Queens", slug: "queens", count: 14 },
  5: { prefix: "si", name: "Staten Island", slug: "staten-island", count: 3 },
};
const TOL = Number(process.env.SIMPLIFY_DEG ?? 0.00002);

const round = (p) => [Math.round(p[0] * 1e5) / 1e5, Math.round(p[1] * 1e5) / 1e5];

function segDist(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const l2 = dx * dx + dy * dy;
  if (l2 === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l2));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

function rdp(pts, tol) {
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = segDist(pts[i], pts[a], pts[b]);
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

function cleanRing(ring) {
  const pts = ring.map(round).filter((p, i, a) => i === 0 || p[0] !== a[i - 1][0] || p[1] !== a[i - 1][1]);
  const out = TOL > 0 && pts.length > 4 ? rdp(pts, TOL) : pts;
  return out.length >= 4 ? out : pts; // never collapse a ring below a valid polygon
}

const data = JSON.parse(readFileSync(input, "utf8"));
const features = data.type === "FeatureCollection" ? data.features : [data];

const byCd = new Map(); // BoroCD -> polygons[]
const skipped = [];
for (const f of features) {
  const key = Object.keys(f.properties ?? {}).find((k) => ["borocd", "boro_cd"].includes(k.toLowerCase()));
  const cd = Number(f.properties?.[key]);
  const boro = Math.floor(cd / 100), num = cd % 100;
  if (!BOROUGHS[boro] || num < 1 || num > BOROUGHS[boro].count) { skipped.push(String(f.properties?.[key])); continue; }
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : null;
  if (!polys) { skipped.push(`${cd} (${g.type})`); continue; }
  byCd.set(cd, [...(byCd.get(cd) ?? []), ...polys.map((poly) => poly.map(cleanRing))]);
}

const rows = [...byCd.entries()].sort((a, b) => a[0] - b[0]).map(([cd, polys]) => {
  const boro = BOROUGHS[Math.floor(cd / 100)], num = cd % 100;
  const geometry = polys.length === 1 ? { type: "Polygon", coordinates: polys[0] } : { type: "MultiPolygon", coordinates: polys };
  const fc = { type: "FeatureCollection", features: [{ type: "Feature", geometry, properties: { BoroCD: cd } }] };
  return { cd, boro, id: `${boro.prefix}-cb-${num}`, name: `${boro.name} Community Board ${num}`, geo: JSON.stringify(fc) };
});

mkdirSync(outDir, { recursive: true });
for (const [digit, boro] of Object.entries(BOROUGHS)) {
  const mine = rows.filter((r) => String(Math.floor(r.cd / 100)) === digit);
  if (!mine.length) continue;
  const values = mine.map((r) => `  ('${r.id}', '${r.name}', '${r.boro.name}', $j$${r.geo}$j$)`).join(",\n");
  const sql = `-- ${boro.name}: ${mine.length} boards. Generated by scripts/seed_boards.mjs from NYC Open Data dataset 5crt-au7u.
-- Requires board m-cb-3 to exist (its ticket types are copied to new boards). Existing boards keep their
-- name, ticket types and flags; only boundary_geojson is written.
insert into public.boards (id, name, borough, ticket_types, boundary_geojson)
select v.id, v.name, v.borough, (select ticket_types from public.boards where id = 'm-cb-3'), v.geo::jsonb
from (values
${values}
) as v(id, name, borough, geo)
on conflict (id) do update set boundary_geojson = excluded.boundary_geojson;
`;
  const file = join(outDir, `boards_${boro.slug}.sql`);
  writeFileSync(file, sql);
  console.log(`${file}: ${mine.length} boards, ${(sql.length / 1024).toFixed(0)} KB`);
}

console.log(`districts kept: ${rows.length}; skipped (joint interest areas or unrecognized): ${skipped.length}${skipped.length ? " [" + skipped.join(", ") + "]" : ""}`);
if (rows.length !== 59 && !allowPartial) {
  console.error(`expected 59 community districts, got ${rows.length}. Check the input file, or pass --allow-partial.`);
  process.exit(2);
}
