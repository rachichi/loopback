// Copies the matching and minutes prompts into their Edge Functions as TypeScript strings, since a
// function deployed with the Supabase MCP tool can't count on reading other files at runtime.
// The prompt's source of truth stays evals/prompts/tickets/tickets-<version>.md, where the harness runs it.
//
// Usage: node scripts/build_match_prompt.mjs           (after editing the prompt)
//        node scripts/build_match_prompt.mjs --check   (CI: fails if the copy is stale)
import { readFileSync, writeFileSync } from "node:fs";

const prompts = [
  { version: "v6", source: "evals/prompts/tickets/tickets-v6.md", target: "supabase/functions/match-transcript/prompt.ts" },
  { version: "v1", source: "evals/prompts/minutes/minutes-v1.md", target: "supabase/functions/generate-minutes/prompt.ts" },
];
const check = process.argv.includes("--check");
let stale = false;
for (const { version, source, target } of prompts) {
  const text = readFileSync(source, "utf8");
  const module =
    `// Generated by scripts/build_match_prompt.mjs from ${source}. Do not edit.\n` +
    `export const PROMPT_VERSION = ${JSON.stringify(version)};\n` +
    `export const PROMPT = ${JSON.stringify(text)};\n`;
  if (check) {
    let current = "";
    try { current = readFileSync(target, "utf8"); } catch { /* missing counts as stale */ }
    if (current !== module) {
      console.error(`${target} is out of date with ${source}. Run node scripts/build_match_prompt.mjs.`);
      stale = true;
    } else console.log(`${target} matches ${source}.`);
  } else {
    writeFileSync(target, module);
    console.log(`Wrote ${target} from ${source}`);
  }
}
if (stale) process.exit(1);
