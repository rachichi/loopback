// Writes supabase/seed.sql: the bundled sample tickets as INSERTs for the tickets table.
// Usage: node scripts/make_supabase_seed.mjs   (then paste the file into the Supabase SQL editor)
import { writeFileSync } from "node:fs";
import { createServer } from "vite";

// The ticket data imports transcripts with Vite's ?raw, so load it through Vite.
const server = await createServer({ server: { middlewareMode: true }, appType: "custom", logLevel: "error" });
const { initialTickets } = await server.ssrLoadModule("/src/goldTickets.ts");
const { toRow } = await server.ssrLoadModule("/src/db.ts");
await server.close();

// Array columns are typed by schema.sql; an empty array can't tell text[] from jsonb on its own.
const textArrayColumns = new Set(["meeting_ids"]);
const sql = (value, column) => {
  if (value === null) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (textArrayColumns.has(column)) return `array[${value.map((item) => sql(item)).join(", ")}]::text[]`;
  if (typeof value === "object") return `${sql(JSON.stringify(value))}::jsonb`;
  return `'${value.replace(/'/g, "''")}'`;
};

// The bundled sample tickets come from Manhattan CB3's meetings, whatever board the app is set to.
const rows = initialTickets.map((ticket) => ({ ...toRow(ticket), board: "m-cb-3" }));
const columns = Object.keys(rows[0]);
const values = rows.map((row) => `  (${columns.map((column) => sql(row[column], column)).join(", ")})`);
writeFileSync(
  "supabase/seed.sql",
  `-- Generated by scripts/make_supabase_seed.mjs. Run after schema.sql; re-running skips tickets that already exist.\n` +
    `insert into public.tickets (${columns.join(", ")}) values\n${values.join(",\n")}\non conflict (id) do nothing;\n`,
);
console.log(`Wrote supabase/seed.sql with ${rows.length} tickets`);
